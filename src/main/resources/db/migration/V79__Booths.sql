-- Booth inventory from the exhibitor agreement floor plan (Addis International Hall, 120 booths).
CREATE TABLE IF NOT EXISTS booth (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code VARCHAR(10) NOT NULL,
    block VARCHAR(4) NOT NULL,
    map_col INTEGER NOT NULL,
    map_row INTEGER NOT NULL,
    booth_type VARCHAR(20) NOT NULL DEFAULT 'STANDARD',
    size_sqm INTEGER NOT NULL DEFAULT 9,
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    reservation_id UUID REFERENCES sponsorship_reservation(id) ON DELETE SET NULL,
    hold_expires_at TIMESTAMP,
    notes VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_booth_code ON booth (code);
CREATE INDEX IF NOT EXISTS ix_booth_reservation ON booth (reservation_id);
